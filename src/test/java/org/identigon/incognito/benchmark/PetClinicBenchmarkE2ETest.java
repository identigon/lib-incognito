/**
 * Phase-7 benchmark: Spring PetClinic. A real schema exercising features no synthetic test combined —
 * {@code GENERATED BY DEFAULT AS IDENTITY} PKs, a PK-less join table with a {@code UNIQUE} constraint
 * ({@code vet_specialties}), a functional unique index on {@code pets}, and a small relational graph
 * ({@code owner → pet → visit}, {@code vet → vet_specialties → specialty}). Schema and data come from
 * the staged fixture under {@code resources/benchmarks/petclinic}. Requires Docker.
 */
@TestInstance(TestInstance.Lifecycle.PER_CLASS)
class PetClinicBenchmarkE2ETest {

    private PostgreSQLContainer pg;
    private DataSource sourceDs;
    private DataSource targetDs;

    @BeforeAll
    void setUp() throws Exception {
        assumeDockerAvailable("PetClinic");

        String schema = resource("/benchmarks/petclinic/schema.sql");
        String data = resource("/benchmarks/petclinic/data.sql");

        pg = new PostgreSQLContainer(TestPostgres.IMAGE)
            .withDatabaseName("petclinic_source").withUsername("test").withPassword("test");
        pg.start();

        sourceDs = dataSource(pg.getJdbcUrl(), pg.getUsername(), pg.getPassword());
        execute(sourceDs, schema);
        execute(sourceDs, data);

        targetDs = createTargetDatabase(pg, "petclinic_target");
        execute(targetDs, schema);
    }

    @AfterAll
    void tearDown() {
        if (pg != null) pg.stop();
    }

    @Test
    void petClinicClonesCoherently() throws Exception {
        Assumptions.assumeTrue(sourceDs != null, "Docker/PostgreSQL not available");

        PipelineResult result = IncognitoPipeline.builder()
            .source(sourceDs).target(targetDs).ephemeralSalt().policy(loadPolicy("/benchmarks/petclinic/policy.yaml"))
            .stage(new SchemaDiscoveryStage())
            .stage(new TableTransformLoadStage())
            .stage(new VerificationStage())
            .build().execute();
        assertTrue(result.success(), "PetClinic should clone successfully");

        emitAndVerifyDpiaReport(result.report(), "petclinic");

        try (Connection conn = targetDs.getConnection()) {
            // Row volumes preserved.
            assertEquals(6, scalar(conn, "SELECT COUNT(*) FROM vets"));
            assertEquals(3, scalar(conn, "SELECT COUNT(*) FROM specialties"));
            assertEquals(5, scalar(conn, "SELECT COUNT(*) FROM vet_specialties"));
            assertEquals(6, scalar(conn, "SELECT COUNT(*) FROM types"));
            assertEquals(10, scalar(conn, "SELECT COUNT(*) FROM owners"));
            assertEquals(13, scalar(conn, "SELECT COUNT(*) FROM pets"));
            assertEquals(4, scalar(conn, "SELECT COUNT(*) FROM visits"));

            // Referential integrity across the graph.
            assertEquals(0, scalar(conn, "SELECT COUNT(*) FROM pets p WHERE NOT EXISTS (SELECT 1 FROM types t WHERE t.id=p.type_id)"));
            assertEquals(0, scalar(conn, "SELECT COUNT(*) FROM pets p WHERE p.owner_id IS NOT NULL AND NOT EXISTS (SELECT 1 FROM owners o WHERE o.id=p.owner_id)"));
            assertEquals(0, scalar(conn, "SELECT COUNT(*) FROM visits v WHERE v.pet_id IS NOT NULL AND NOT EXISTS (SELECT 1 FROM pets p WHERE p.id=v.pet_id)"));
            assertEquals(0, scalar(conn, "SELECT COUNT(*) FROM vet_specialties vs WHERE NOT EXISTS (SELECT 1 FROM vets v WHERE v.id=vs.vet_id) OR NOT EXISTS (SELECT 1 FROM specialties s WHERE s.id=vs.specialty_id)"));

            // The PK-less join table's pairs stay unique and count-preserved.
            assertEquals(5, scalar(conn, "SELECT COUNT(DISTINCT (vet_id, specialty_id)) FROM vet_specialties"));

            // PII fabricated: no real owner surname or telephone survives.
            assertEquals(0, scalar(conn, "SELECT COUNT(*) FROM owners WHERE last_name IN ('Franklin','Davis','Rodriquez','McTavish','Coleman','Black','Escobito','Schroeder','Estaban')"));
            assertEquals(0, scalar(conn, "SELECT COUNT(*) FROM owners WHERE telephone IN ('6085551023','6085551749','6085558763','6085553198','6085552765','6085552654','6085555387','6085557683','6085559435','6085555487')"));

            // Operational categoricals kept real.
            assertEquals(3, scalar(conn, "SELECT COUNT(*) FROM specialties WHERE name IN ('radiology','surgery','dentistry')"));

            // Sequences resynced: a default-PK insert into a GENERATED BY DEFAULT table succeeds.
            try (Statement stmt = conn.createStatement()) {
                stmt.execute("INSERT INTO owners (first_name, last_name, address, city, telephone) VALUES ('x','y','z','c','1')");
            }
            assertEquals(11, scalar(conn, "SELECT COUNT(*) FROM owners"));
        }
    }
}
