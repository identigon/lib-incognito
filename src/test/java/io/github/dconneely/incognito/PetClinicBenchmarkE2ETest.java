/**
 * Phase-7 benchmark: Spring PetClinic. A real schema exercising features no synthetic test combined —
 * {@code GENERATED BY DEFAULT AS IDENTITY} PKs, a PK-less join table with a {@code UNIQUE} constraint
 * ({@code vet_specialties}), a functional unique index on {@code pets}, and a small relational graph
 * ({@code owner → pet → visit}, {@code vet → vet_specialties → specialty}). Schema and data come from
 * the staged fixture under {@code resources/benchmarks/petclinic}. Requires Docker.
 */
@TestInstance(TestInstance.Lifecycle.PER_CLASS)
class PetClinicBenchmarkE2ETest {

    private PostgreSQLContainer pg;
    private DataSource sourceDs;
    private DataSource targetDs;

    @BeforeAll
    void setUp() throws Exception {
        boolean dockerAvailable;
        try {
            dockerAvailable = org.testcontainers.DockerClientFactory.instance().isDockerAvailable();
        } catch (Exception e) {
            dockerAvailable = false;
        }
        Assumptions.assumeTrue(dockerAvailable, "Docker not available — skipping PetClinic benchmark");

        String schema = resource("/benchmarks/petclinic/schema.sql");
        String data = resource("/benchmarks/petclinic/data.sql");

        pg = new PostgreSQLContainer("postgres:16-alpine")
            .withDatabaseName("petclinic_source").withUsername("test").withPassword("test");
        pg.start();

        try (Connection conn = DriverManager.getConnection(pg.getJdbcUrl(), pg.getUsername(), pg.getPassword())) {
            conn.setAutoCommit(true);
            try (Statement stmt = conn.createStatement()) {
                stmt.execute(schema);
                stmt.execute(data);
            }
        }

        String jdbcBase = "jdbc:postgresql://" + pg.getHost() + ":" + pg.getFirstMappedPort() + "/";
        try (Connection admin = DriverManager.getConnection(jdbcBase + "postgres", pg.getUsername(), pg.getPassword())) {
            admin.setAutoCommit(true);
            try (Statement stmt = admin.createStatement()) {
                stmt.execute("CREATE DATABASE petclinic_target");
            }
        }
        String targetUrl = jdbcBase + "petclinic_target";
        try (Connection conn = DriverManager.getConnection(targetUrl, pg.getUsername(), pg.getPassword())) {
            conn.setAutoCommit(true);
            try (Statement stmt = conn.createStatement()) { stmt.execute(schema); }
        }

        sourceDs = new SimpleDataSource(pg.getJdbcUrl(), pg.getUsername(), pg.getPassword());
        targetDs = new SimpleDataSource(targetUrl, pg.getUsername(), pg.getPassword());
    }

    @AfterAll
    void tearDown() {
        if (pg != null) pg.stop();
    }

    private AnonymisationPolicy policy() {
        return AnonymisationPolicy.builder()
            .table("vets", t -> t
                .column("id", ColumnRole.PRIMARY_KEY, SurrogateStrategy.SEQUENTIAL_LONG)
                .column("first_name", ColumnRole.DIRECT_ID, DirectIdStrategy.ALTEREGO_GENERIC)
                .column("last_name", ColumnRole.DIRECT_ID, DirectIdStrategy.ALTEREGO_GENERIC))
            .table("specialties", t -> t
                .column("id", ColumnRole.PRIMARY_KEY, SurrogateStrategy.SEQUENTIAL_LONG)
                .column("name", ColumnRole.PAYLOAD))
            .table("vet_specialties", t -> t
                .column(ColumnPolicy.builder("vet_id").role(ColumnRole.FOREIGN_KEY).references("vets", "id").build())
                .column(ColumnPolicy.builder("specialty_id").role(ColumnRole.FOREIGN_KEY).references("specialties", "id").build()))
            .table("types", t -> t
                .column("id", ColumnRole.PRIMARY_KEY, SurrogateStrategy.SEQUENTIAL_LONG)
                .column("name", ColumnRole.PAYLOAD))
            .table("owners", t -> t
                .column("id", ColumnRole.PRIMARY_KEY, SurrogateStrategy.SEQUENTIAL_LONG)
                .column("first_name", ColumnRole.DIRECT_ID, DirectIdStrategy.ALTEREGO_GENERIC)
                .column("last_name", ColumnRole.DIRECT_ID, DirectIdStrategy.ALTEREGO_GENERIC)
                .column("address", ColumnRole.DIRECT_ID, DirectIdStrategy.ALTEREGO_GENERIC)
                .column("city", ColumnRole.PAYLOAD)
                .column("telephone", ColumnRole.DIRECT_ID, DirectIdStrategy.ALTEREGO_PHONE))
            .table("pets", t -> t
                .column("id", ColumnRole.PRIMARY_KEY, SurrogateStrategy.SEQUENTIAL_LONG)
                .column("name", ColumnRole.DIRECT_ID, DirectIdStrategy.ALTEREGO_GENERIC)
                .column(ColumnPolicy.builder("birth_date").role(ColumnRole.QUASI_ID).quasiIdStrategy(QuasiIdStrategy.SYNTHESISE).build())
                .column(ColumnPolicy.builder("type_id").role(ColumnRole.FOREIGN_KEY).references("types", "id").build())
                .column(ColumnPolicy.builder("owner_id").role(ColumnRole.FOREIGN_KEY).references("owners", "id").build()))
            .table("visits", t -> t
                .column("id", ColumnRole.PRIMARY_KEY, SurrogateStrategy.SEQUENTIAL_LONG)
                .column(ColumnPolicy.builder("pet_id").role(ColumnRole.FOREIGN_KEY).references("pets", "id").build())
                .column(ColumnPolicy.builder("visit_date").role(ColumnRole.QUASI_ID).quasiIdStrategy(QuasiIdStrategy.SYNTHESISE).build())
                .column("description", ColumnRole.PAYLOAD))
            .build();
    }

    @Test
    void petClinicClonesCoherently() throws Exception {
        Assumptions.assumeTrue(sourceDs != null, "Docker/PostgreSQL not available");

        PipelineResult result = IncognitoPipeline.builder()
            .source(sourceDs).target(targetDs).ephemeralSalt().policy(policy())
            .stage(new SchemaDiscoveryStage())
            .stage(new TableTransformLoadStage())
            .stage(new VerificationStage())
            .build().execute();
        assertTrue(result.success(), "PetClinic should clone successfully");

        try (Connection conn = targetDs.getConnection()) {
            // Row volumes preserved.
            assertEquals(6, scalar(conn, "SELECT COUNT(*) FROM vets"));
            assertEquals(3, scalar(conn, "SELECT COUNT(*) FROM specialties"));
            assertEquals(5, scalar(conn, "SELECT COUNT(*) FROM vet_specialties"));
            assertEquals(6, scalar(conn, "SELECT COUNT(*) FROM types"));
            assertEquals(10, scalar(conn, "SELECT COUNT(*) FROM owners"));
            assertEquals(13, scalar(conn, "SELECT COUNT(*) FROM pets"));
            assertEquals(4, scalar(conn, "SELECT COUNT(*) FROM visits"));

            // Referential integrity across the graph.
            assertEquals(0, scalar(conn, "SELECT COUNT(*) FROM pets p WHERE NOT EXISTS (SELECT 1 FROM types t WHERE t.id=p.type_id)"));
            assertEquals(0, scalar(conn, "SELECT COUNT(*) FROM pets p WHERE p.owner_id IS NOT NULL AND NOT EXISTS (SELECT 1 FROM owners o WHERE o.id=p.owner_id)"));
            assertEquals(0, scalar(conn, "SELECT COUNT(*) FROM visits v WHERE v.pet_id IS NOT NULL AND NOT EXISTS (SELECT 1 FROM pets p WHERE p.id=v.pet_id)"));
            assertEquals(0, scalar(conn, "SELECT COUNT(*) FROM vet_specialties vs WHERE NOT EXISTS (SELECT 1 FROM vets v WHERE v.id=vs.vet_id) OR NOT EXISTS (SELECT 1 FROM specialties s WHERE s.id=vs.specialty_id)"));

            // The PK-less join table's pairs stay unique and count-preserved.
            assertEquals(5, scalar(conn, "SELECT COUNT(DISTINCT (vet_id, specialty_id)) FROM vet_specialties"));

            // PII fabricated: no real owner surname or telephone survives.
            assertEquals(0, scalar(conn, "SELECT COUNT(*) FROM owners WHERE last_name IN ('Franklin','Davis','Rodriquez','McTavish','Coleman','Black','Escobito','Schroeder','Estaban')"));
            assertEquals(0, scalar(conn, "SELECT COUNT(*) FROM owners WHERE telephone IN ('6085551023','6085551749','6085558763','6085553198','6085552765','6085552654','6085555387','6085557683','6085559435','6085555487')"));

            // Operational categoricals kept real.
            assertEquals(3, scalar(conn, "SELECT COUNT(*) FROM specialties WHERE name IN ('radiology','surgery','dentistry')"));

            // Sequences resynced: a default-PK insert into a GENERATED BY DEFAULT table succeeds.
            try (Statement stmt = conn.createStatement()) {
                stmt.execute("INSERT INTO owners (first_name, last_name, address, city, telephone) VALUES ('x','y','z','c','1')");
            }
            assertEquals(11, scalar(conn, "SELECT COUNT(*) FROM owners"));
        }
    }

    private long scalar(Connection conn, String sql) throws SQLException {
        try (Statement stmt = conn.createStatement(); ResultSet rs = stmt.executeQuery(sql)) {
            rs.next();
            return rs.getLong(1);
        }
    }

    private static String resource(String path) throws Exception {
        try (var in = PetClinicBenchmarkE2ETest.class.getResourceAsStream(path)) {
            if (in == null) throw new IllegalStateException("missing test resource: " + path);
            return new String(in.readAllBytes(), StandardCharsets.UTF_8);
        }
    }

    private record SimpleDataSource(String url, String user, String password) implements DataSource {
        @Override public Connection getConnection() throws SQLException { return DriverManager.getConnection(url, user, password); }
        @Override public Connection getConnection(String u, String p) throws SQLException { return DriverManager.getConnection(url, u, p); }
        @Override public java.io.PrintWriter getLogWriter() { return null; }
        @Override public void setLogWriter(java.io.PrintWriter out) {}
        @Override public int getLoginTimeout() { return 0; }
        @Override public void setLoginTimeout(int seconds) {}
        @Override public java.util.logging.Logger getParentLogger() { return java.util.logging.Logger.getGlobal(); }
        @Override public <T> T unwrap(Class<T> iface) throws SQLException { throw new SQLException("Not a wrapper"); }
        @Override public boolean isWrapperFor(Class<?> iface) { return false; }
    }
}
